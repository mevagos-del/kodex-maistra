import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import ts from 'typescript';
import { loadSpells } from './load-spells.mjs';

const moduleCache = new Map();

function loadLocalModule(path) {
  const filename = [path, `${path}.ts`, resolve(path, 'index.ts')]
    .find((candidate) => existsSync(candidate) && candidate.endsWith('.ts'));
  if (!filename) throw new Error(`Missing TypeScript module: ${path}`);
  if (moduleCache.has(filename)) return moduleCache.get(filename);

  const exports = {};
  moduleCache.set(filename, exports);
  const compiled = ts.transpileModule(readFileSync(filename, 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  }).outputText;
  new Function('require', 'exports', compiled)(
    (specifier) => loadLocalModule(resolve(dirname(filename), specifier)),
    exports,
  );
  return exports;
}

const rulesRoot = resolve('src/data/rules');
const { officialRaces } = loadLocalModule(resolve(rulesRoot, 'races'));
const { officialClasses } = loadLocalModule(resolve(rulesRoot, 'classes'));
const { officialItems } = loadLocalModule(resolve(rulesRoot, 'items'));
const { officialFeats } = loadLocalModule(resolve(rulesRoot, 'feats.ts'));
const { officialConditions } = loadLocalModule(resolve(rulesRoot, 'conditions.ts'));
const { officialRules } = loadLocalModule(resolve(rulesRoot, 'rules.ts'));
const { officialBestiary } = loadLocalModule(resolve(rulesRoot, 'bestiary.ts'));
const { officialSpells } = await loadSpells();

const section = (key, label, path, records, mapRecord) => records.map((record) => ({
  section: key,
  sectionLabel: label,
  path: `${path}/${record.slug}`,
  slug: record.slug,
  ...mapRecord(record),
}));

const rawEntries = [
  ...section('races', 'Раси', '/races', officialRaces, (entry) => ({ nameUk: entry.nameUk, nameOriginal: entry.nameOriginal })),
  ...section('classes', 'Класи', '/classes', officialClasses, (entry) => ({ nameUk: entry.nameUk, nameOriginal: entry.nameOriginal })),
  ...section('feats', 'Риси', '/feats', officialFeats, (entry) => ({ nameUk: entry.nameUk, nameOriginal: entry.nameEn })),
  ...section('spells', 'Закляття', '/spells', officialSpells, (entry) => ({ nameUk: entry.nameUk, nameOriginal: entry.nameEn })),
  ...section('items', 'Предмети', '/items', officialItems, (entry) => ({ nameUk: entry.nameUk, nameOriginal: entry.nameOriginal })),
  ...section('conditions', 'Стани', '/conditions', officialConditions, (entry) => ({
    nameUk: entry.nameUk,
    nameOriginal: entry.nameEn,
    keywords: `${entry.summary} ${entry.slug === 'frightened' ? 'переляканий страх' : ''}`.trim(),
  })),
  ...section('rules', 'Правила', '/rules', officialRules, (entry) => ({
    nameUk: entry.nameUk,
    nameOriginal: entry.nameOriginal,
    keywords: [entry.category, ...(entry.keywords ?? [])].join(' '),
  })),
  ...section('bestiary', 'Бестіарій', '/bestiary', officialBestiary, (entry) => ({ nameUk: entry.nameUk, nameOriginal: entry.nameOriginal })),
];

// A few catalog variants share one canonical detail route. The homepage exposes each route once.
const entries = [...new Map(rawEntries.map((entry) => [entry.path, entry])).values()]
  .sort((left, right) => left.section.localeCompare(right.section) || left.nameUk.localeCompare(right.nameUk, 'uk'));

const target = resolve('src/data/homeReferenceIndex.generated.ts');
const header = `// Generated by scripts/generate-home-reference-index.mjs. Do not edit manually.\n`;
const types = `export type HomeReferenceSection = 'races' | 'classes' | 'feats' | 'spells' | 'items' | 'conditions' | 'rules' | 'bestiary';\n\n`;
const output = `${header}${types}export const HOME_REFERENCE_INDEX = ${JSON.stringify(entries, null, 2)} as const;\n`;
writeFileSync(target, output, 'utf8');
console.log(`Generated ${entries.length} homepage search entries in ${target}`);
